-- =============================================================================
-- fft_top_tb.vhd
-- =============================================================================
-- Testbench za kompletan FFT akcelerator (fft_top)
--
-- Sta testira:
--   TEST 1: Reset i pocetno stanje
--   TEST 2: Ucitavanje N odbiraka, provera in_spreman handshaking-a
--   TEST 3: Izvrsavanje FFT-a, merenje broja ciklusa
--   TEST 4: Ocitavanje rezultata i ispis u fajl za Python verifikaciju
--   TEST 5: Verifikacija pika u spektru
--
-- Test signal:
--   x[n] = 0.5 * sin(2*pi*5*n/N)
--   Ocekivani spektar: pik na k=5 i k=N-5
--
-- Izlaz:
--   fft_output.txt - rezultati za Python verifikaciju (numpy.fft poredjenje)
--
-- Pokretanje (GHDL):
--   ghdl -a --std=08 fft_top_tb.vhd
--   ghdl -e --std=08 fft_top_tb
--   ghdl -r --std=08 fft_top_tb --wave=fft.ghw
-- =============================================================================

library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;
use IEEE.MATH_REAL.ALL;
use STD.TEXTIO.ALL;
-- NAPOMENA: IEEE.STD_LOGIC_TEXTIO nije potreban - pisemo samo integere i
-- stringove u fajl. Njegovo ukljucivanje zahteva GHDL flag -fsynopsys.

entity fft_top_tb is
end fft_top_tb;

architecture sim of fft_top_tb is

    -- ?? Parametri (mali N za brzu simulaciju) ?????????????????????????????????
    constant FFT_N           : positive := 1024;
    constant LOG2_N          : positive := 10;
    constant SIRINA_PODATAKA : positive := 16;
    constant PIPE_DUBINA     : positive := 5;
    constant CLK_PERIOD      : time     := 10 ns;
    constant SCALE           : real     := 32767.0;

    -- Timeout za watchdog (ako simulacija zapne)
    constant SIM_TIMEOUT     : time     := 500 us;

    -- ?? DUT signali ???????????????????????????????????????????????????????????
    signal clk              : std_logic := '0';
    signal rst              : std_logic := '1';
    signal start            : std_logic := '0';
    signal obrada           : std_logic;
    signal kraj             : std_logic;
    signal in_valid         : std_logic := '0';
    signal in_re            : signed(SIRINA_PODATAKA-1 downto 0) := (others => '0');
    signal in_im            : signed(SIRINA_PODATAKA-1 downto 0) := (others => '0');
    signal in_spreman       : std_logic;
    signal rezultat_addr    : unsigned(LOG2_N-1 downto 0) := (others => '0');
    signal rezultat_re      : signed(SIRINA_PODATAKA-1 downto 0);
    signal rezultat_im      : signed(SIRINA_PODATAKA-1 downto 0);
    signal rezultat_spreman : std_logic;
    signal dbg_stepen       : unsigned(3 downto 0);
    signal dbg_bank_sel     : std_logic;

    -- ?? Brojac ciklusa (za merenje latencije) ?????????????????????????????????
    signal cycle_count     : integer := 0;
    signal fft_start_cycle : integer := 0;
    signal fft_end_cycle   : integer := 0;

    -- Zastavica koja gasi watchdog kada testovi zavrse
    signal sim_done : boolean := false;

    -- ?? Test signal ???????????????????????????????????????????????????????????
    type sample_array_t is array(0 to FFT_N-1) of integer;

    -- ?? Generisanje test signala ??????????????????????????????????????????????
    -- x[n] = ampl * sin(2*pi*bin*n/N), kvantizovano u Q1.15
    -- Amplituda 0.5 da se izbegne overflow u prvim stupnjevima
    function gen_sine(n : integer; bin : integer; ampl : real) return integer is
        variable val : real;
    begin
        val := ampl * sin(2.0 * MATH_PI * real(bin) * real(n) / real(FFT_N));
        return integer(round(val * SCALE));
    end function;

    -- ISPRAVKA: test_input je sada konstanta izracunata u elaboration fazi.
    -- Ranije je bio signal punjen u petlji, sto je nepotrebno komplikovalo
    -- vremensku sinhronizaciju (signal dobija vrednost tek posle wait-a).
    function init_test_input return sample_array_t is
        variable t : sample_array_t;
    begin
        for n in 0 to FFT_N-1 loop
            t(n) := gen_sine(n, 5, 0.5);
        end loop;
        return t;
    end function;

    constant TEST_INPUT : sample_array_t := init_test_input;

begin

    -- ?? DUT ???????????????????????????????????????????????????????????????????
    DUT : entity work.fft_top
        generic map (
            FFT_N           => FFT_N,
            LOG2_N          => LOG2_N,
            SIRINA_PODATAKA => SIRINA_PODATAKA,
            PIPE_DUBINA     => PIPE_DUBINA
        )
        port map (
            clk              => clk,
            rst              => rst,
            start            => start,
            obrada           => obrada,
            kraj             => kraj,
            in_valid         => in_valid,
            in_re            => in_re,
            in_im            => in_im,
            in_spreman       => in_spreman,
            rezultat_addr    => rezultat_addr,
            rezultat_re      => rezultat_re,
            rezultat_im      => rezultat_im,
            rezultat_spreman => rezultat_spreman,
            dbg_stepen       => dbg_stepen,
            dbg_bank_sel     => dbg_bank_sel
        );

    -- ?? Clock ?????????????????????????????????????????????????????????????????
    clk <= not clk after CLK_PERIOD / 2;

    -- ?? Brojac ciklusa ????????????????????????????????????????????????????????
    cycle_counter : process(clk)
    begin
        if rising_edge(clk) then
            cycle_count <= cycle_count + 1;
        end if;
    end process;

    -- ?? DODATO: Watchdog ??????????????????????????????????????????????????????
    -- Prekida simulaciju ako zapne, umesto da visi beskonacno.
    -- Bez ovoga, greska u handshaking-u znaci da simulacija stoji bez poruke.
    watchdog : process
    begin
        wait for SIM_TIMEOUT;
        if not sim_done then
            report "WATCHDOG TIMEOUT: simulacija nije zavrsena u " &
                   time'image(SIM_TIMEOUT) &
                   ". Proveri handshaking signale (in_spreman, kraj)."
                severity failure;
        end if;
        wait;
    end process watchdog;

    -- ?? Glavni test proces ????????????????????????????????????????????????????
    stimulus : process
        file     out_file     : text;
        variable out_line     : line;
        variable re_val       : integer;
        variable im_val       : integer;
        variable magnitude    : real;
        variable max_mag      : real    := 0.0;
        variable max_bin      : integer := 0;
        variable total_cycles : integer;
    begin

        report "=== Test signal: sinus @ bin 5, N=" &
               integer'image(FFT_N) & " ===";

        -- ?????????????????????????????????????????????????????????????????????
        -- TEST 1: Reset
        -- ?????????????????????????????????????????????????????????????????????
        report "=== TEST 1: Reset ===";
        rst <= '1';
        wait for CLK_PERIOD * 5;
        rst <= '0';
        wait for CLK_PERIOD * 2;

        assert obrada = '0' report "T1: obrada treba biti 0" severity error;
        assert kraj   = '0' report "T1: kraj treba biti 0"   severity error;
        report "TEST 1: PASS";

        -- ?????????????????????????????????????????????????????????????????????
        -- TEST 2: Ucitavanje podataka
        -- ?????????????????????????????????????????????????????????????????????
        report "=== TEST 2: Ucitavanje " & integer'image(FFT_N) & " odbiraka ===";

        start <= '1';
        wait until rising_edge(clk);
        start <= '0';
        wait until rising_edge(clk);
        fft_start_cycle <= cycle_count;

        -- ISPRAVKA: "wait until in_spreman = '1'" ceka DOGADJAJ (promenu), a ne
        -- stanje. Ako je signal vec '1', cekanje nikad ne zavrsi i simulacija
        -- visi. Zato prvo proveravamo trenutnu vrednost.
        if in_spreman /= '1' then
            wait until in_spreman = '1';
        end if;
        report "  in_spreman aktivan, pocinje ucitavanje...";

        -- Saljemo N odbiraka
        -- ISPRAVKA: postavljamo podatke PRE ivice takta, ne posle, i
        -- postujemo handshaking (saljemo samo kada je in_spreman = '1')
        for n in 0 to FFT_N-1 loop
            in_valid <= '1';
            in_re    <= to_signed(TEST_INPUT(n), SIRINA_PODATAKA);
            in_im    <= to_signed(0, SIRINA_PODATAKA);
            wait until rising_edge(clk);

            -- Ako DUT nije spreman, cekamo (back-pressure)
            while in_spreman /= '1' loop
                wait until rising_edge(clk);
            end loop;
        end loop;

        in_valid <= '0';
        in_re    <= (others => '0');
        in_im    <= (others => '0');

        report "TEST 2: Ucitano " & integer'image(FFT_N) & " odbiraka [PASS]";

        -- ?????????????????????????????????????????????????????????????????????
        -- TEST 3: Izvrsavanje FFT-a
        -- ?????????????????????????????????????????????????????????????????????
        report "=== TEST 3: Izvrsavanje FFT-a ===";
        report "  Cekam kraj signal...";

        -- ISPRAVKA: ista zamka kao gore - prvo provera stanja, pa cekanje.
        -- Timeout ostaje kao dodatna zastita.
        if kraj /= '1' then
            wait until kraj = '1' for 200 us;
        end if;
        fft_end_cycle <= cycle_count;
        wait for 1 ns;

        assert kraj = '1'
            report "T3 GRESKA: FFT nije zavrsen u ocekivanom vremenu. " &
                   "Zadnji stupanj: " & integer'image(to_integer(dbg_stepen))
            severity failure;

        total_cycles := fft_end_cycle - fft_start_cycle;
        report "TEST 3: FFT zavrsen!";
        report "  Ukupno ciklusa: " & integer'image(total_cycles);
        report "  @ 100 MHz = " & real'image(real(total_cycles) * 0.01) & " us";
        report "  Teorijski: " &
               integer'image(FFT_N + LOG2_N*(FFT_N/2 + PIPE_DUBINA)) & " ciklusa";

        -- ?????????????????????????????????????????????????????????????????????
        -- TEST 4: Ocitavanje rezultata i upis u fajl
        -- ?????????????????????????????????????????????????????????????????????
        report "=== TEST 4: Ocitavanje rezultata ===";

        file_open(out_file, "fft_output.txt", write_mode);

        write(out_line, string'("# FFT rezultat iz VHDL simulacije"));
        writeline(out_file, out_line);
        write(out_line, string'("# N=" & integer'image(FFT_N) &
                                " ulaz: sinus @ bin 5, amplituda 0.5"));
        writeline(out_file, out_line);
        write(out_line, string'("# format: k,re,im"));
        writeline(out_file, out_line);

        for k in 0 to FFT_N-1 loop
            rezultat_addr <= to_unsigned(k, LOG2_N);
            wait until rising_edge(clk);   -- adresa registrovana
            wait until rising_edge(clk);   -- BRAM latencija 1 ciklus
            wait for 1 ns;                 -- izbegni race na ivici takta

            re_val := to_integer(rezultat_re);
            im_val := to_integer(rezultat_im);

            write(out_line, k);
            write(out_line, string'(","));
            write(out_line, re_val);
            write(out_line, string'(","));
            write(out_line, im_val);
            writeline(out_file, out_line);

            magnitude := sqrt(real(re_val)**2 + real(im_val)**2);
            if magnitude > max_mag then
                max_mag := magnitude;
                max_bin := k;
            end if;

            if k < 12 then
                report "  X[" & integer'image(k) & "] = " &
                       integer'image(re_val) & " + j*" &
                       integer'image(im_val) &
                       "  |X| = " & integer'image(integer(magnitude));
            end if;
        end loop;

        file_close(out_file);

        report "TEST 4: Rezultati upisani u fft_output.txt [PASS]";
        report "  Najveca magnituda: bin " & integer'image(max_bin) &
               " |X| = " & integer'image(integer(max_mag));

        -- ?????????????????????????????????????????????????????????????????????
        -- TEST 5: Verifikacija pika na bin 5
        -- ?????????????????????????????????????????????????????????????????????
        report "=== TEST 5: Verifikacija spektra ===";

        if max_bin = 5 or max_bin = FFT_N-5 then
            report "TEST 5: PASS - pik detektovan na bin " &
                   integer'image(max_bin) & " (ocekivano 5 ili " &
                   integer'image(FFT_N-5) & ")";
        else
            report "TEST 5: UPOZORENJE - pik na bin " &
                   integer'image(max_bin) &
                   " (ocekivano 5 ili " & integer'image(FFT_N-5) & ")"
                severity warning;
        end if;

        -- ?????????????????????????????????????????????????????????????????????
        -- Kraj
        -- ?????????????????????????????????????????????????????????????????????
        wait for CLK_PERIOD * 10;
        sim_done <= true;              -- gasi watchdog
        wait for CLK_PERIOD;

        report "=== SIMULACIJA ZAVRSENA ===" severity note;
        report "Sledeci korak: python verify_fft.py fft_output.txt";
        wait;

    end process stimulus;

end sim;